"""Regenerate src/activity.ts from each project's git history.

Needs the GitHub CLI (`gh`) signed in. Run from the repo root:
    python3 scripts/update-activity.py
"""

import json
import math
import subprocess
from datetime import datetime

# Project name (as in src/data.ts) -> GitHub repo
PROJECTS = {
    'Byte Blasters': 'nagahole/byte-blasters',
    'MRI → CT Synthesis': 'COMP3988/COMP3988_F12_01',
    'PocketWise': 'nagahole/pocketwise',
    'Generic Minimaxer': 'nagahole/generic_minimaxer',
    'ITCH Feed Handler': 'nagahole/cpp-itch',
    'Scope': 'nagahole/scope',
}
BINS = 26  # points per line, matching the card sparklines
GAP_DAYS = 120  # a pause this long ends a project's main stretch of work
SIGMA = 1.1  # smoothing, in bins


def commit_dates(repo):
    out = subprocess.run(
        ['gh', 'api', f'repos/{repo}/commits?per_page=100', '--paginate', '--jq', '.[].commit.author.date'],
        capture_output=True, text=True, check=True,
    ).stdout
    return sorted(datetime.strptime(line, '%Y-%m-%dT%H:%M:%SZ') for line in out.split())


def activity(dates):
    # Main stretch of work: stop at the first long pause (later README or cleanup commits)
    window = [dates[0]]
    for d in dates[1:]:
        if (d - window[-1]).days > GAP_DAYS:
            break
        window.append(d)

    start, end = window[0].timestamp(), window[-1].timestamp()
    span = max(end - start, 1)
    counts = [0] * BINS
    for d in window:
        counts[min(int((d.timestamp() - start) / span * BINS), BINS - 1)] += 1

    # Gaussian smoothing so sparse histories still read as a curve
    weights = lambda i: [math.exp(-((i - j) ** 2) / (2 * SIGMA ** 2)) for j in range(BINS)]
    smooth = [sum(c * w for c, w in zip(counts, weights(i))) / sum(weights(i)) for i in range(BINS)]
    peak = max(smooth)

    first, last = f'{window[0]:%b %Y}', f'{window[-1]:%b %Y}'
    period = first if first == last else f'{first} – {last}'
    return len(window), period, [round(v / peak, 3) for v in smooth]


lines = [
    "// Generated by scripts/update-activity.py from each project's git history:",
    '// commits per period over its main stretch of work (ending at the first pause',
    '// longer than four months), smoothed and scaled so the busiest period is 1.',
    'export const activity: Record<string, { commits: number; period: string; values: number[] }> = {',
]
for name, repo in PROJECTS.items():
    commits, period, values = activity(commit_dates(repo))
    print(f'{name:22} {commits:4} commits  {period}')
    lines += [
        f'  {json.dumps(name, ensure_ascii=False)}: {{'.replace('"', "'"),
        f'    commits: {commits},',
        f"    period: '{period}',",
        f"    values: [{', '.join(str(v) for v in values)}],",
        '  },',
    ]
lines.append('}')

with open('src/activity.ts', 'w') as f:
    f.write('\n'.join(lines) + '\n')
